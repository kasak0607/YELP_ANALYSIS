  JOIN ANALYTICS_SENTIMENT_MONTHLY S
    ON M.BUSINESS_ID = S.BUSINESS_ID
   AND M.YEAR_MONTH = S.YEAR_MONTH
  JOIN ANALYTICS_RESTAURANT_CHECKINS_MONTHLY C
    ON M.BUSINESS_ID = C.BUSINESS_ID
   AND M.YEAR_MONTH = C.YEAR_MONTH
),
NORMALIZED AS (
  SELECT *,
    ROUND((REVIEWS_COUNT - COALESCE(REVIEWS_LAST_MONTH,0)) / NULLIF(COALESCE(REVIEWS_LAST_MONTH,1),0),3) AS REVIEWS_VELOCITY,
    ROUND((CHECKINS_COUNT - COALESCE(CHECKINS_LAST_MONTH,0)) / NULLIF(COALESCE(CHECKINS_LAST_MONTH,1),0),3) AS CHECKINS_VELOCITY
  FROM BASE
)
SELECT
  BUSINESS_ID,
  YEAR_MONTH,
  AVG_RATING,
  REVIEW_COUNT AS TOTAL_USER_REVIEWS,
  REVIEWS_COUNT,
  CHECKINS_COUNT,
  RATING_VOLATILITY,
  NEG_SENTIMENT_RATIO,
  IS_OPEN,
  REVIEWS_VELOCITY,
  CHECKINS_VELOCITY,
  CASE WHEN REVIEWS_VELOCITY < -0.30 THEN 1 ELSE 0 END AS REVIEWS_SHARP_DROP,
  CASE WHEN CHECKINS_VELOCITY < -0.30 THEN 1 ELSE 0 END AS CHECKINS_SHARP_DROP,
  CASE WHEN NEG_SENTIMENT_RATIO > 0.30 THEN 1 ELSE 0 END AS NEGATIVE_SURGE,
  ROUND(
      (REVIEWS_SHARP_DROP * 2.5) +
      (CHECKINS_SHARP_DROP * 2.0) +
      (NEGATIVE_SURGE * 3.5) +
      (RATING_VOLATILITY * 1.8)
  , 3) AS RISK_SIGNAL_SCORE
FROM NORMALIZED;

